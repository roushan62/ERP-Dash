'use strict';
// PDF generator (jsPDF + autotable). Runs in the Electron main process.
const fs = require('fs');
const jsPDF = require('jspdf').jsPDF;
const autoTable = require('jspdf-autotable');

function inr(n) {
  const sign = n < 0 ? '-' : '';
  const abs = Math.abs(Number(n) || 0).toFixed(2);
  const parts = abs.split('.');
  let int = parts[0];
  const last3 = int.length > 3 ? int.slice(-3) : int;
  const front = int.length > 3 ? int.slice(0, -3) : '';
  const f = front ? front.replace(/\B(?=(\d{2})+(?!\d))/g, ',') + ',' : '';
  return sign + '₹ ' + f + last3 + '.' + parts[1];
}

function buildHeader(doc, data) {
  const c = data.company || {};
  const y = 15;
  doc.setFillColor(255, 255, 255);
  doc.rect(0, 0, 210, 30, 'F');
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.setTextColor(30, 64, 175);
  doc.text(c.name || 'VyaparBooks', 15, y + 4);
  doc.setFontSize(8.5);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(30, 41, 59);
  const addr = [c.address, [c.city, c.state, c.pincode].filter(Boolean).join(', '), c.phone && ('Phone: ' + c.phone), c.email && ('Email: ' + c.email), c.gstin && ('GSTIN: ' + c.gstin)].filter(Boolean).join('\n');
  doc.text(addr || '', 15, y + 12, { lineHeightFactor: 1.25 });
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(13);
  doc.text(data.title || 'Report', 130, y + 6, { align: 'right' });
  doc.setFontSize(8);
  doc.setFont('helvetica', 'normal');
  if (data.subtitle) doc.text(data.subtitle, 130, y + 13, { align: 'right' });
  doc.text('Generated: ' + new Date().toLocaleString(), 130, y + 19, { align: 'right' });
  doc.setDrawColor(30, 64, 175);
  doc.setLineWidth(0.6);
  doc.line(15, 34, 195, 34);
  doc.setFontSize(8);
  doc.setTextColor(100, 116, 139);
  doc.text('Generated by VyaparBooks', 15, 288);
}

function generate(data, savePath) {
  const doc = new jsPDF({ unit: 'mm', format: 'a4' });
  buildHeader(doc, data);
  if (data.paragraphs) {
    doc.setFontSize(9);
    doc.setTextColor(30, 41, 59);
    let y = 42;
    for (const p of data.paragraphs) {
      const lines = doc.splitTextToSize(p, 180);
      doc.text(lines, 15, y);
      y += lines.length * 4.5 + 4;
    }
  }
  if (data.columns && data.columns.length && data.rows && data.rows.length) {
    autoTable(doc, {
      startY: 42,
      head: [data.columns.map((c) => c.label || c)],
      body: data.rows.map((r) => data.columns.map((c) => (c.format ? c.format(r) : r[c.key !== undefined ? c.key : c]) )),
      styles: { fontSize: 8, cellPadding: 2, textColor: [30, 41, 59] },
      headStyles: { fillColor: [30, 64, 175], textColor: [255, 255, 255], fontStyle: 'bold' },
      alternateRowStyles: { fillColor: [248, 250, 252] },
      columnStyles: Object.fromEntries(data.columns.map((c, i) => [i, c.num ? { halign: 'right' } : {}])),
      margin: { left: 15, right: 15, top: 42, bottom: 18 },
      didDrawPage: () => buildHeader(doc, data),
    });
    const finalY = doc.lastAutoTable.finalY || 42;
    if (data.totals && data.totals.length) {
      doc.setFontSize(9);
      doc.setFont('helvetica', 'bold');
      let y = finalY + 6;
      for (const t of data.totals) {
        doc.setTextColor(30, 41, 59);
        doc.text(String(t.label), 145, y);
        doc.text(t.amount !== undefined ? inr(t.amount) : String(t.value || ''), 195, y, { align: 'right' });
        y += 5;
      }
    }
  }
  doc.save = doc.save || (() => {});
  fs.writeFileSync(savePath, Buffer.from(doc.output('arraybuffer')));
  return savePath;
}

module.exports = { generate, inr };
